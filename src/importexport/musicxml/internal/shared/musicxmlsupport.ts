/**
 muse::String::toInt(bool* ok): strtol of the whole string (leading white space and a sign allowed); 0 and not ok
 unless all characters are used
 */
export function strToInt(s: string, ok?: { v: boolean }): number {
    const m = /^[ \t\n\v\f\r]*([+-]?\d+)$/.exec(s)
    if (ok) {
        ok.v = !!m
    }
    if (!m) {
        return 0
    }
    const v = parseInt(m[1], 10)
    // static_cast<int>(strtol(...))
    return v | 0
}

/** muse::String::toDouble(bool* ok): strtod: the number at the start of the string (ok if there is one) */
export function strToDouble(s: string, ok?: { v: boolean }): number {
    const m = /^[ \t\n\v\f\r]*([+-]?(?:(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?|inf(?:inity)?|nan))/i.exec(s)
    if (ok) {
        ok.v = !!m
    }
    if (!m) {
        return 0
    }
    const t = m[1].toLowerCase()
    if (t.endsWith('inf') || t.endsWith('infinity')) {
        return t.startsWith('-') ? -Infinity : Infinity
    }
    if (t.endsWith('nan')) {
        return NaN
    }
    return parseFloat(m[1])
}

/** muse::String::simplified() (QString::simplified): white space trimmed, internal white space runs replaced by one space */
export function simplified(s: string): string {
    return s.replace(/\s+/g, ' ').trim()
}

/** muse::String::trimmed(): leading and trailing white space (std::isspace) removed */
export function trimmed(s: string): string {
    return s.replace(/^[ \t\n\v\f\r]+|[ \t\n\v\f\r]+$/g, '')
}

