//---------------------------------------------------------
//   checkAtEndElement
//---------------------------------------------------------

export function checkAtEndElement(e: XmlStreamReader, expName: string): string {
    if (e.isEndElement() && e.name() === expName) {
        return ''
    }

    return mtrc('iex_musicxml', 'expected token type and name ‘EndElement %1’, actual ‘%2 %3’')
        .replace('%1', expName).replace('%2', e.tokenString()).replace('%3', e.name())
}

//---------------------------------------------------------
//   MusicXmlSupport -- MusicXML import support functions
//---------------------------------------------------------

export class MusicXmlSupport {
    /**
     Convert a string in \a s into an int. Set *ok to true iff conversion was
     successful. \a s may end with ".0", as is generated by Audiveris 3.2 and up,
     in elements <divisions>, <duration>, <alter> and <sound> attributes
     dynamics and tempo.
     In case of error val return a default value of 0.
     Note that non-integer values cannot be handled by mscore.
     */
    static stringToInt(s: string, ok?: { v: boolean }): number {
        let str = s
        if (s.endsWith('.0')) {
            str = s.slice(0, s.length - 2)
        }
        return strToInt(str, ok)
    }

    /** Convert MusicXML note type to fraction. */
    static noteTypeToFraction(type: string): Fraction {
        switch (type) {
        case '1024th': return new Fraction(1, 1024)
        case '512th': return new Fraction(1, 512)
        case '256th': return new Fraction(1, 256)
        case '128th': return new Fraction(1, 128)
        case '64th': return new Fraction(1, 64)
        case '32nd': return new Fraction(1, 32)
        case '16th': return new Fraction(1, 16)
        case 'eighth': return new Fraction(1, 8)
        case 'quarter': return new Fraction(1, 4)
        case 'half': return new Fraction(1, 2)
        case 'whole': return new Fraction(1, 1)
        case 'breve': return new Fraction(2, 1)
        case 'long': return new Fraction(4, 1)
        case 'maxima': return new Fraction(8, 1)
        default: return new Fraction(0, 0)
        }
    }

    /** Convert note type, number of dots and actual and normal notes into a duration */
    static calculateFraction(type: string, dots: number, normalNotes: number, actualNotes: number): Fraction {
        // type
        let f = MusicXmlSupport.noteTypeToFraction(type)
        if (f.isValid()) {
            // dot(s)
            const fNoDots = f
            for (let i = 0; i < dots; ++i) {
                f = f.plus(fNoDots.div(new Fraction(2 << i, 1)))
            }
            // tuplet
            if (actualNotes > 0 && normalNotes > 0) {
                f = f.times(normalNotes)
                f = f.div(new Fraction(actualNotes, 1))
            }
            // clean up (just in case)
            f = f.reduced()
        }
        return f
    }
}

