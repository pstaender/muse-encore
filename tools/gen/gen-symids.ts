import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const src = process.argv[2]
if (!src) {
    console.error('usage: tsx tools/gen/gen-symids.ts <MuseScore source dir>')
    process.exit(1)
}

const HEADER = `/*
 * SPDX-License-Identifier: GPL-3.0-only
 * MuseScore-Web — port of MuseScore Studio (https://github.com/musescore/MuseScore)
 * Copyright (C) 2021-2026 MuseScore Limited and others
 *
 * GENERATED by tools/gen/gen-symids.ts - do not edit manually!
 */
`

function stripComments(s: string): string {
    return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')
}

// --- SymId enum
const symidP = stripComments(readFileSync(join(src, 'src/engraving/types/symid_p.h'), 'utf8'))
const enumBody = symidP.match(/enum class SymId \{([\s\S]*?)\};/)![1]
const ids = enumBody.split(',').map(s => s.trim()).filter(s => s.length > 0)

// --- names
const symnames = readFileSync(join(src, 'src/engraving/types/symnames.cpp'), 'utf8')
const namesBody = stripComments(symnames.match(/s_symNames \{ \{([\s\S]*?)\} \};/)![1])
const names = [...namesBody.matchAll(/"([^"]*)"/g)].map(m => m[1])


const oldBody = stripComments(symnames.match(/s_oldNameToSymIdHash \{([\s\S]*?)\};/)![1])
const oldNames = [...oldBody.matchAll(/\{\s*"([^"]*)",\s*SymId::(\w+)\s*\}/g)].map(m => [m[1], m[2]])

if (ids.length !== names.length + 1) { // + lastSym
    throw new Error(`SymId count ${ids.length} != names count ${names.length} + 1`)
}

// --- codes
const glyphnames = JSON.parse(readFileSync(join(src, 'fonts/smufl/glyphnames.json'), 'utf8'))
const codes: number[] = []
const altCodes: number[] = []
for (const name of names) {
    const g = glyphnames[name]
    codes.push(g?.codepoint ? parseInt(g.codepoint.slice(2), 16) : 0)
    altCodes.push(g?.alternateCodepoint ? parseInt(g.alternateCodepoint.slice(2), 16) : 0)
}
codes.push(0)
altCodes.push(0)

let out = HEADER + `
// Port of src/engraving/types/symid.h, symid_p.h

export enum SmuflAnchorId {
    stemDownNW,
    stemUpSE,
    stemDownSW,
    stemUpNW,
    cutOutNE,
    cutOutNW,
    cutOutSE,
    cutOutSW,
    opticalCenter,
}

export enum SymId {
${ids.map(id => `    ${id},`).join('\n')}
}

export type SymIdList = SymId[]
`
writeFileSync('src/engraving/types/symid.ts', out)

out = HEADER + `
// Data of src/engraving/types/symnames.cpp and the SMuFL code points from fonts/smufl/glyphnames.json

import { SymId } from './symid'

export const SYM_NAMES: readonly string[] = ${JSON.stringify(names)}

export const OLD_SYM_NAMES: ReadonlyArray<[string, SymId]> = [
${oldNames.map(([n, id]) => `    [${JSON.stringify(n)}, SymId.${id}],`).join('\n')}
]

/** SMuFL code point per SymId (0 = none) */
export const SMUFL_CODES: readonly number[] = ${JSON.stringify(codes)}

/** alternate code point (Unicode Musical Symbols block) per SymId (0 = none) */
export const SMUFL_ALT_CODES: readonly number[] = ${JSON.stringify(altCodes)}
`
writeFileSync('src/engraving/types/symnamesdata.ts', out)
console.log(`generated ${ids.length} SymIds, ${oldNames.length} old names`)
